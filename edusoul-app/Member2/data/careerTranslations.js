export function translateCareer(text, lang = 'en') {
  if (!text || typeof text !== 'string') return text;
  if (lang === 'en') return text;

  const entry = careerMessages[text.trim()];
  if (entry) {
    if (lang === 'si' && entry[0]) return entry[0];
    if (lang === 'ta' && entry[1]) return entry[1];
  }
  return text;
}
